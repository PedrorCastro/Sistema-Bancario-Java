CREATE TABLE tb_clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    cpf VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL
);

CREATE TABLE tb_contas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero INTEGER,
    titular_id BIGINT,
    saldo NUMERIC(38, 2),
    CONSTRAINT fk_tb_contas_titular
        FOREIGN KEY (titular_id) REFERENCES tb_clientes (id)
);

CREATE TABLE tb_contas_correntes (
    id BIGINT PRIMARY KEY,
    limite NUMERIC(38, 2),
    CONSTRAINT fk_tb_contas_correntes_conta
        FOREIGN KEY (id) REFERENCES tb_contas (id)
);

CREATE TABLE tb_contas_poupancas (
    id BIGINT PRIMARY KEY,
    CONSTRAINT fk_tb_contas_poupancas_conta
        FOREIGN KEY (id) REFERENCES tb_contas (id)
);

CREATE TABLE tb_transacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor NUMERIC(38, 2),
    tipo VARCHAR(255),
    data TIMESTAMP(6) WITHOUT TIME ZONE,
    conta_id BIGINT,
    CONSTRAINT fk_tb_transacoes_conta
        FOREIGN KEY (conta_id) REFERENCES tb_contas (id)
);

CREATE INDEX idx_tb_contas_titular_id ON tb_contas (titular_id);
CREATE INDEX idx_tb_transacoes_conta_data ON tb_transacoes (conta_id, data);
